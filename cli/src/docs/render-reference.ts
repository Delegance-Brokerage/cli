/** Escape characters MDX would read as JSX or an expression. */
function mdxText(text: string): string {
  return text.replace(/[<>{}]/g, (c) => `\\${c}`);
}

function cell(text: string): string {
  return mdxText(text).replace(/\|/g, '\\|');
}

function optionRow(opt: Option): string {
  const def = opt.defaultValue !== undefined && opt.defaultValue !== true && opt.defaultValue !== false
    ? ` (default: \`${String(opt.defaultValue)}\`)`
    : '';
  return `| \`${opt.flags}\` | ${cell(opt.description ?? '')}${def} |`;
}

function renderLeaf(path: string, cmd: Command, out: string[]): void {
  out.push(`### \`${path}\``, '');
  if (cmd.aliases().length) out.push(`Alias: ${cmd.aliases().map(a => `\`${a}\``).join(', ')}`, '');
  out.push(mdxText(cmd.description()), '');
  out.push('```bash', `delegance ${path} ${cmd.usage()}`.trimEnd(), '```', '');

  const examples = EXAMPLES[path];
  if (examples) out.push('```bash', ...examples, '```', '');

  const options = cmd.options.filter(o => o.long !== '--help');
  if (options.length) {
    out.push('| Flag | Description |', '|------|-------------|', ...options.map(optionRow), '');
  }
}

export function renderCommandReference(program: Command): string {
  const out: string[] = [
    '{/* Generated by cli/scripts/gen-command-docs.ts from the live command tree. Do not edit by hand. */}',
    '',
    '# Commands Reference',
    '',
    `Every \`delegance\` command, generated from the CLI itself (v${program.version()}). Most commands take \`--json\`.`,
    '',
  ];

  for (const top of program.commands) {
    out.push('---', '', `## \`${top.name()}\``, '');
    if (top.aliases().length) out.push(`Alias: ${top.aliases().map(a => `\`${a}\``).join(', ')}`, '');
    out.push(mdxText(top.description()), '');

    if (top.commands.length === 0) {
      renderLeaf(top.name(), top, out);
      continue;
    }
    for (const sub of top.commands) {
      renderLeaf(`${top.name()} ${sub.name()}`, sub, out);
    }
  }

  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

/** Every command path in the tree, e.g. "doc upload". */
export function commandPaths(program: Command): string[] {
  const paths: string[] = [];
  for (const top of program.commands) {
    if (top.commands.length === 0) paths.push(top.name());
    for (const sub of top.commands) paths.push(`${top.name()} ${sub.name()}`);
  }
  return paths;
}
